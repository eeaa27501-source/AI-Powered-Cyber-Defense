import streamlit as st
import pandas as pd

st.set_page_config(page_title="AI-Powered Cyber Defense", page_icon="🛡️", layout="wide")
st.title("🛡️ AI-Powered Cyber Defense")
st.caption("Educational security-log analysis demo")
st.warning("This is a rule-based demonstration, not a trained AI model or a production security system. Use only the included sample data or logs you are authorized to analyze.")

def analyze(df):
    results = []
    for _, row in df.iterrows():
        event = str(row.get("event_type", "")).strip().lower()
        count = int(row.get("failed_attempts", 0) or 0)
        host = str(row.get("source_ip", "Unknown"))
        user = str(row.get("username", "Unknown"))
        if event == "failed_login" and count >= 5:
            results.append({"Source IP": host, "User": user, "Alert": "Repeated failed login attempts", "Severity": "High", "Recommendation": "Review the account activity and enable appropriate account protections."})
        if event == "malware_detected":
            results.append({"Source IP": host, "User": user, "Alert": "Malware detection event", "Severity": "High", "Recommendation": "Follow your organization's incident-response process and review the affected endpoint."})
        if event == "suspicious_process":
            results.append({"Source IP": host, "User": user, "Alert": "Suspicious process event", "Severity": "Medium", "Recommendation": "Verify whether the process is expected and review its source."})
        if event == "unusual_login_time":
            results.append({"Source IP": host, "User": user, "Alert": "Unusual login time", "Severity": "Low", "Recommendation": "Confirm whether the login was expected."})
    return pd.DataFrame(results, columns=["Source IP", "User", "Alert", "Severity", "Recommendation"])

st.subheader("Upload a CSV log file")
uploaded = st.file_uploader("Choose a CSV file", type=["csv"])
sample = pd.DataFrame([
    {"timestamp":"2026-10-30 08:15:00","source_ip":"192.0.2.10","username":"student1","event_type":"failed_login","failed_attempts":7},
    {"timestamp":"2026-10-30 09:20:00","source_ip":"198.51.100.8","username":"student2","event_type":"malware_detected","failed_attempts":0},
    {"timestamp":"2026-10-30 11:05:00","source_ip":"203.0.113.15","username":"student3","event_type":"suspicious_process","failed_attempts":0},
    {"timestamp":"2026-10-30 23:40:00","source_ip":"192.0.2.25","username":"student4","event_type":"unusual_login_time","failed_attempts":0},
])
if uploaded:
    try:
        data = pd.read_csv(uploaded)
    except Exception as e:
        st.error(f"Could not read CSV: {e}")
        st.stop()
else:
    st.caption("No file uploaded — using safe synthetic sample data.")
    data = sample

required = {"source_ip", "username", "event_type"}
missing = required - set(data.columns)
if missing:
    st.error("Missing required columns: " + ", ".join(sorted(missing)))
    st.stop()

if "failed_attempts" not in data.columns:
    data["failed_attempts"] = 0

st.subheader("Input log records")
st.dataframe(data, use_container_width=True)

alerts = analyze(data)
st.subheader("Analysis results")
a, b, c = st.columns(3)
a.metric("Records analyzed", len(data))
b.metric("Alerts found", len(alerts))
c.metric("High severity", int((alerts["Severity"] == "High").sum()) if len(alerts) else 0)

if alerts.empty:
    st.success("No alerts were generated by the demo rules.")
else:
    st.dataframe(alerts, use_container_width=True)
    st.download_button("Download alerts as CSV", alerts.to_csv(index=False).encode("utf-8"), "security_alerts.csv", "text/csv")

st.caption("Rule-based educational analysis only. It does not scan networks, block attacks, or replace professional security tools.")
